"""Data models for the BYS pipeline."""

from __future__ import annotations
from dataclasses import dataclass, field, asdict
from typing import Any
import json
from pathlib import Path

import yaml
from pydantic import BaseModel, Field as PydField


@dataclass
class Lead:
    """Raw lead from targeting."""
    firstName: str
    lastName: str
    companyName: str
    email: str = ""
    linkedinUrl: str = ""
    headline: str = ""
    seniority: str = ""
    industry: str = ""
    techStack: str = ""
    icebreaker: str = ""

    @classmethod
    def from_dict(cls, data: dict[str, Any]) -> Lead:
        known_fields = {f.name for f in cls.__dataclass_fields__.values()}
        filtered = {k: v for k, v in data.items() if k in known_fields}
        return cls(**filtered)


@dataclass
class EnrichedLead(Lead):
    """Lead enriched with Firecrawl + RapidAPI data."""
    firecrawl_context: dict[str, Any] = field(default_factory=dict)
    linkedin_profile: dict[str, Any] = field(default_factory=dict)
    intent_score: int = 0
    enrichment_errors: list[str] = field(default_factory=list)

    @classmethod
    def from_lead(cls, lead: Lead) -> EnrichedLead:
        return cls(**{k: v for k, v in asdict(lead).items()
                      if k in {f.name for f in Lead.__dataclass_fields__.values()}})


@dataclass
class LeadBrief:
    """Structured analysis of a lead by the Analyst agent."""
    firstName: str
    lastName: str
    companyName: str
    sector: str = ""              # secteur reel (pas juste "SaaS B2B")
    company_moment: str = ""      # ce que vit l'entreprise maintenant
    person_story: str = ""        # parcours et ce qui rend cette personne unique
    person_x_moment: str = ""     # intersection personne x moment
    daily_reality: str = ""       # quotidien concret de cette personne dans son role


@dataclass
class Strategy:
    """Strategic decisions by the Strategist agent."""
    firstName: str
    lastName: str
    angle_type: str = ""          # parcours+momentum, role+news, etc.
    chosen_pain: str = ""         # pain du CAB-P le plus pertinent pour ce lead
    chosen_benefit: str = ""      # benefice a mettre en avant
    information_gap: str = ""     # le gap de curiosite a creer
    key_question: str = ""        # la question qui reste dans la tete
    why_this_angle: str = ""      # justification du choix


